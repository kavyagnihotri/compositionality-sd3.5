"""
Compare CLIC CogVLM and RedCaps Text Encoders

This script compares the two CLIC variants to understand their differences:
1. Weight statistics comparison
2. Embedding similarity on test prompts
3. Architecture differences (if any)
"""

import torch
import numpy as np
from pathlib import Path
from transformers import CLIPTextModelWithProjection, CLIPTokenizer
import matplotlib.pyplot as plt


COGVLM_DIR = "/mnt/lustre/work/hein/hof217/stable_diffusion/z4-cogvlm_custom_sd35/converted_text_encoder_CogVLM"
REDCAPS_DIR = "/mnt/lustre/work/hein/hof217/stable_diffusion/z0-custom_sd35_clic/converted_text_encoder"


def check_both_models_exist():
    """Check if both converted models exist."""
    cogvlm_path = Path(COGVLM_DIR)
    redcaps_path = Path(REDCAPS_DIR)
    
    if not cogvlm_path.exists():
        print(f"ERROR: CogVLM model not found at {COGVLM_DIR}")
        return False
    
    if not redcaps_path.exists():
        print(f"ERROR: RedCaps model not found at {REDCAPS_DIR}")
        return False
    
    print("Both models found")
    return True


def compare_architectures(model_cogvlm, model_redcaps):
    """Compare model architectures."""
    print("\nArchitecture Comparison:")
    
    config_cogvlm = model_cogvlm.config
    config_redcaps = model_redcaps.config
    
    attrs = ['hidden_size', 'num_hidden_layers', 'num_attention_heads', 
             'intermediate_size', 'vocab_size', 'max_position_embeddings',
             'projection_dim', 'hidden_act']
    
    differences = []
    for attr in attrs:
        val_cogvlm = getattr(config_cogvlm, attr, None)
        val_redcaps = getattr(config_redcaps, attr, None)
        
        match = "MATCH" if val_cogvlm == val_redcaps else "DIFFER"
        print(f"  {attr}: CogVLM={val_cogvlm}, RedCaps={val_redcaps} [{match}]")
        
        if val_cogvlm != val_redcaps:
            differences.append(attr)
    
    if differences:
        print(f"\nArchitectural differences found in: {', '.join(differences)}")
    else:
        print("\nArchitectures are identical")
    
    return len(differences) == 0


def compare_weight_statistics(model_cogvlm, model_redcaps):
    """Compare weight statistics between models."""
    print("\nWeight Statistics Comparison:")
    
    state_dict_cogvlm = model_cogvlm.state_dict()
    state_dict_redcaps = model_redcaps.state_dict()
    
    # Check if they have the same keys
    keys_cogvlm = set(state_dict_cogvlm.keys())
    keys_redcaps = set(state_dict_redcaps.keys())
    
    if keys_cogvlm != keys_redcaps:
        print(f"  WARNING: Different weight keys")
        print(f"  CogVLM only: {keys_cogvlm - keys_redcaps}")
        print(f"  RedCaps only: {keys_redcaps - keys_cogvlm}")
        return False
    
    print(f"  Both models have {len(keys_cogvlm)} weight tensors")
    
    # Compare statistics for each weight
    key_examples = [
        'text_model.embeddings.token_embedding.weight',
        'text_model.encoder.layers.0.self_attn.q_proj.weight',
        'text_model.encoder.layers.0.mlp.fc1.weight',
        'text_projection.weight'
    ]
    
    print("\n  Sample weight statistics:")
    for key in key_examples:
        if key in state_dict_cogvlm:
            w_cogvlm = state_dict_cogvlm[key].float()
            w_redcaps = state_dict_redcaps[key].float()
            
            # Compute statistics
            diff = (w_cogvlm - w_redcaps).abs()
            max_diff = diff.max().item()
            mean_diff = diff.mean().item()
            
            # Compute cosine similarity
            cos_sim = torch.nn.functional.cosine_similarity(
                w_cogvlm.flatten().unsqueeze(0),
                w_redcaps.flatten().unsqueeze(0)
            ).item()
            
            print(f"\n  {key}:")
            print(f"    Shape: {w_cogvlm.shape}")
            print(f"    Max diff: {max_diff:.6f}")
            print(f"    Mean diff: {mean_diff:.6f}")
            print(f"    Cosine similarity: {cos_sim:.6f}")
    
    return True


def compare_embeddings(model_cogvlm, tokenizer_cogvlm, model_redcaps, tokenizer_redcaps):
    """Compare embeddings generated by both models."""
    print("\nEmbedding Comparison:")
    
    test_prompts = [
        "a red ball above a blue cube",
        "a cat sitting to the left of a dog",
        "a tree below the clouds",
        "an object on top of another object"
    ]
    
    model_cogvlm.eval()
    model_redcaps.eval()
    
    all_similarities = []
    
    with torch.no_grad():
        for prompt in test_prompts:
            # Generate embeddings from both models
            tokens_cogvlm = tokenizer_cogvlm(prompt, return_tensors="pt", padding="max_length", truncation=True)
            tokens_redcaps = tokenizer_redcaps(prompt, return_tensors="pt", padding="max_length", truncation=True)
            
            outputs_cogvlm = model_cogvlm(**tokens_cogvlm)
            outputs_redcaps = model_redcaps(**tokens_redcaps)
            
            # Compare text embeddings (pooled)
            emb_cogvlm = outputs_cogvlm.text_embeds[0]
            emb_redcaps = outputs_redcaps.text_embeds[0]
            
            # Compute similarity
            cos_sim = torch.nn.functional.cosine_similarity(
                emb_cogvlm.unsqueeze(0),
                emb_redcaps.unsqueeze(0)
            ).item()
            
            # Compute L2 distance
            l2_dist = torch.norm(emb_cogvlm - emb_redcaps).item()
            
            all_similarities.append(cos_sim)
            
            print(f"\n  Prompt: '{prompt}'")
            print(f"    Cosine similarity: {cos_sim:.6f}")
            print(f"    L2 distance: {l2_dist:.6f}")
    
    avg_similarity = np.mean(all_similarities)
    print(f"\n  Average cosine similarity: {avg_similarity:.6f}")
    
    if avg_similarity > 0.95:
        print("  Embeddings are very similar")
    elif avg_similarity > 0.80:
        print("  Embeddings are moderately similar")
    else:
        print("  Embeddings are quite different")
    
    return True


def plot_layer_differences(model_cogvlm, model_redcaps):
    """Calculates and plots the mean weight difference per transformer layer."""
    layer_diffs = []
    layer_indices = []
    
    state_cog = model_cogvlm.state_dict()
    state_red = model_redcaps.state_dict()
    
    # Iterate through the number of layers defined in the config
    num_layers = model_cogvlm.config.num_hidden_layers
    
    print(f"\nCalculating differences for {num_layers} layers...")
    
    for i in range(num_layers):
        # We'll aggregate differences for all weights in a specific layer
        # (e.g., self_attn, layer_norms, and mlp)
        layer_prefix = f"text_model.encoder.layers.{i}."
        keys = [k for k in state_cog.keys() if k.startswith(layer_prefix)]
        
        diffs = []
        for key in keys:
            w1 = state_cog[key].float()
            w2 = state_red[key].float()
            # Calculate Mean Absolute Error (MAE) for this specific weight tensor
            mae = torch.abs(w1 - w2).mean().item()
            diffs.append(mae)
        
        # Average the MAE across all components of the layer
        avg_layer_diff = sum(diffs) / len(diffs)
        layer_diffs.append(avg_layer_diff)
        layer_indices.append(i)

    # Plotting
    plt.figure(figsize=(10, 6))
    plt.bar(layer_indices, layer_diffs, color='skyblue', edgecolor='navy')
    plt.xlabel('Transformer Layer Index')
    plt.ylabel('Mean Absolute Difference (Weights)')
    plt.title('Weight Divergence: CogVLM vs RedCaps Encoders')
    plt.xticks(layer_indices)
    plt.grid(axis='y', linestyle='--', alpha=0.7)
    
    # Save the plot
    plt.savefig('layer_differences.png')
    print("Plot saved as 'layer_differences.png'")


def plot_layer_difference_subtraction(model_cogvlm, model_redcaps):
    """
    Plots the direct subtraction of weight magnitudes: CogVLM - RedCaps.
    """
    layer_indices = []
    differences = []
    
    state_cog = model_cogvlm.state_dict()
    state_red = model_redcaps.state_dict()
    num_layers = model_cogvlm.config.num_hidden_layers
    
    for i in range(num_layers):
        layer_prefix = f"text_model.encoder.layers.{i}."
        keys = [k for k in state_cog.keys() if k.startswith(layer_prefix)]
        
        # Calculate mean magnitude for CogVLM
        mag_cog = torch.stack([state_cog[k].float().abs().mean() for k in keys]).mean().item()
        # Calculate mean magnitude for RedCaps
        mag_red = torch.stack([state_red[k].float().abs().mean() for k in keys]).mean().item()
        
        # Simple subtraction
        diff = mag_cog - mag_red
        
        differences.append(diff)
        layer_indices.append(i)

    # --- PLOTTING ---
    plt.figure(figsize=(12, 6))
    colors = ['#1f77b4' if d > 0 else '#ff7f0e' for d in differences]
    
    plt.bar(layer_indices, differences, color=colors, edgecolor='black', alpha=0.8)
    plt.axhline(y=0, color='black', linestyle='-', linewidth=1) # Zero line
    
    # Labeling for clarity
    plt.text(0, max(differences)*0.9, "↑ CogVLM weights are LARGER", fontsize=10, color='#1f77b4', fontweight='bold')
    plt.text(0, min(differences)*0.9, "↓ RedCaps weights are LARGER", fontsize=10, color='#ff7f0e', fontweight='bold')

    plt.title('Weight Magnitude Difference: (CogVLM Mean |w|) - (RedCaps Mean |w|)')
    plt.xlabel('Transformer Layer Index')
    plt.ylabel('Difference in Mean Absolute Weight')
    plt.xticks(layer_indices)
    plt.grid(axis='y', linestyle='--', alpha=0.3)
    
    plt.tight_layout()
    plt.savefig('layer_weight_diff.png')
    print("Subtraction plot saved as 'layer_weight_diff.png'")


